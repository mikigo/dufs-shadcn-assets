// 解析 vscode-icons 映射文件，生成图标查找表
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from "fs"
import { resolve, basename } from "path"

const vscIconsDir = "C:\\Users\\Administrator\\.vscode\\extensions\\vscode-icons-team.vscode-icons-13.0.0"
const mappingPath = resolve(vscIconsDir, "dist/src/vsicons-icon-theme.json")
const iconsSrc = resolve(vscIconsDir, "icons")
const projectRoot = resolve(import.meta.dirname, "..")
const iconsDest = resolve(projectRoot, "src/assets/vsc-icons")
const mapOutput = resolve(projectRoot, "src/generated/vsc-icon-map.ts")

const raw = readFileSync(mappingPath, "utf-8")

function extractSection(raw, sectionName) {
  const startIdx = raw.indexOf(`"${sectionName}"`)
  if (startIdx === -1) return null
  const colonIdx = raw.indexOf(":", startIdx)
  const openIdx = raw.indexOf("{", colonIdx)
  if (openIdx === -1) return null
  let depth = 1
  let i = openIdx + 1
  for (; i < raw.length && depth > 0; i++) {
    if (raw[i] === "{") depth++
    else if (raw[i] === "}") depth--
  }
  return raw.substring(openIdx + 1, i - 1)
}

function parseIconDefs(raw) {
  const defs = {}
  const section = extractSection(raw, "iconDefinitions")
  if (!section) return defs
  // 每个定义: "name": { "iconPath": "..." }
  const re = /"([^"]+)"\s*:\s*\{[^}]*"iconPath"\s*:\s*"([^"]+)"\s*[^}]*\}/g
  let match
  while ((match = re.exec(section)) !== null) {
    defs[match[1]] = match[2]
  }
  return defs
}

function extractIconName(iconPath) {
  return basename(iconPath, ".svg")
}

function parseSection(raw, sectionName, defs) {
  const result = {}
  const section = extractSection(raw, sectionName)
  if (!section) return result
  for (const m of section.matchAll(/"([^"]+)"\s*:\s*"([^"]+)"/g)) {
    result[m[1]] = extractIconName(defs[m[2]] || m[2])
  }
  return result
}

const defs = parseIconDefs(raw)
console.log(`Parsed ${Object.keys(defs).length} icon definitions`)

const exts = parseSection(raw, "fileExtensions", defs)
const files = parseSection(raw, "fileNames", defs)
const folders = parseSection(raw, "folderNames", defs)
const langIds = parseSection(raw, "languageIds", defs)

console.log(`Extensions: ${Object.keys(exts).length}, Filenames: ${Object.keys(files).length}, Folders: ${Object.keys(folders).length}, LanguageIds: ${Object.keys(langIds).length}`)

// 收集被引用的图标（包括所有来源）
const referencedIcons = new Set()
referencedIcons.add("default_file")
referencedIcons.add("default_folder")
referencedIcons.add("default_root_folder")
referencedIcons.add("default_root_folder_opened")
for (const name of Object.values(exts)) referencedIcons.add(name)
for (const name of Object.values(files)) referencedIcons.add(name)
for (const name of Object.values(folders)) referencedIcons.add(name)
for (const name of Object.values(langIds)) referencedIcons.add(name)
console.log(`Unique icons: ${referencedIcons.size}`)

// 拷贝 SVG
if (!existsSync(iconsDest)) mkdirSync(iconsDest, { recursive: true })
let copied = 0
for (const name of referencedIcons) {
  const src = resolve(iconsSrc, name + ".svg")
  const dest = resolve(iconsDest, name + ".svg")
  if (existsSync(src) && !existsSync(dest)) {
    copyFileSync(src, dest)
    copied++
  }
}
console.log(`Copied ${copied} icons to src/assets/vsc-icons`)

// 生成 TypeScript
function formatMap(obj, indent = "  ") {
  return Object.entries(obj)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${indent}"${k}": "${v}"`)
    .join(",\n")
}

const tsContent = `// Auto-generated by generate-vsc-icon-map.mjs
export const extToIcon: Record<string, string> = {
${formatMap(exts)}
}

export const fileNameToIcon: Record<string, string> = {
${formatMap(files)}
}

export const folderNameToIcon: Record<string, string> = {
${formatMap(folders)}
}

export const langToIcon: Record<string, string> = {
${formatMap(langIds)}
}

export const DEFAULT_FILE_ICON = "default_file"
export const DEFAULT_FOLDER_ICON = "default_folder"
`

const genDir = resolve(projectRoot, "src/generated")
if (!existsSync(genDir)) mkdirSync(genDir)

// 生成字符映射表
writeFileSync(mapOutput, tsContent, "utf-8")
console.log(`Generated: ${mapOutput}`)

// 生成图标导入文件
const allIcons = [...referencedIcons].sort()
const importLines = allIcons
  .map(name => `import ${toValidIdent(name)} from "@/assets/vsc-icons/${name}.svg?raw"`)
  .join("\n")
const iconEntries = allIcons
  .map(name => `  "${name}": ${toValidIdent(name)},`)
  .join("\n")

function toValidIdent(name) {
  return "_" + name.replace(/[^a-zA-Z0-9_]/g, "_")
}

const modulesContent = `// Auto-generated icon modules
${importLines}

export const iconModules: Record<string, string> = {
${iconEntries}
}
`

const modulesOutput = resolve(projectRoot, "src/generated/vsc-icon-modules.ts")
writeFileSync(modulesOutput, modulesContent, "utf-8")
console.log(`Generated icon modules: ${modulesOutput}`)